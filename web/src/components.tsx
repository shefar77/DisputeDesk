/** Small presentational components shared by the pages. */

import { useEffect, type ReactNode } from 'react';
import type { CompletenessBand, DisputeStatus, GatherState, UrgencyInfo, WorkflowStepView } from '@shared/index.js';

export function SandboxBanner({ mode }: { mode: string }) {
  // FR-13: on every page. Wording differs by mode but is never absent.
  return (
    <div className="sandbox-banner" role="status">
      <span className="tag">{mode === 'demo' ? 'DEMO' : 'SANDBOX'}</span>
      {mode === 'demo'
        ? 'Demo mode — fixture disputes. Nothing is sent to PayPal. No real money.'
        : 'PayPal SANDBOX — test transactions, no real money.'}
    </div>
  );
}

const URGENCY_TONE: Record<UrgencyInfo['level'], string> = {
  OVERDUE: 'red',
  CRITICAL: 'red',
  URGENT: 'amber',
  SOON: 'blue',
  NORMAL: 'grey',
  NONE: 'grey',
};

/** Colour + glyph + text: three channels, so colour is never the only signal. */
export function UrgencyBadge({ urgency }: { urgency: UrgencyInfo }) {
  return (
    <span className={`badge ${URGENCY_TONE[urgency.level]}`} title={urgency.label}>
      <span className="glyph" aria-hidden="true">{urgency.icon}</span>
      {urgency.label}
    </span>
  );
}

export const BAND_TONE: Record<CompletenessBand, string> = {
  WEAK: 'red',
  PARTIAL: 'amber',
  STRONG: 'blue',
  COMPLETE: 'green',
};

export const BAND_COLOR: Record<string, string> = {
  WEAK: 'var(--red)',
  PARTIAL: 'var(--amber)',
  STRONG: 'var(--blue)',
  COMPLETE: 'var(--green)',
};

export function BandBadge({ band }: { band: string | null }) {
  if (!band) return <span className="badge grey">Not scored</span>;
  return <span className={`badge ${BAND_TONE[band as CompletenessBand] ?? 'grey'}`}>{band.toLowerCase()}</span>;
}

const STATUS_LABEL: Record<DisputeStatus, [string, string]> = {
  OPEN: ['Open', 'blue'],
  WAITING_FOR_SELLER_RESPONSE: ['Awaiting your response', 'amber'],
  WAITING_FOR_BUYER_RESPONSE: ['Awaiting buyer', 'grey'],
  UNDER_REVIEW: ['Under review by PayPal', 'blue'],
  RESOLVED: ['Resolved', 'green'],
  OTHER: ['Other', 'grey'],
};

export function StatusBadge({ status }: { status: DisputeStatus }) {
  const [label, tone] = STATUS_LABEL[status] ?? [status, 'grey'];
  return <span className={`badge ${tone}`}>{label}</span>;
}

const GATHER_LABEL: Record<GatherState, [string, string]> = {
  NOT_STARTED: ['Not gathered', 'grey'],
  GATHERING: ['Gathering…', 'blue'],
  READY_FOR_REVIEW: ['Ready for review', 'green'],
  NEEDS_MANUAL_REVIEW: ['Needs manual review', 'amber'],
  SUBMITTED: ['Submitted', 'grey'],
  FAILED: ['Gathering failed', 'red'],
};

export function GatherBadge({ state }: { state: GatherState }) {
  const [label, tone] = GATHER_LABEL[state] ?? [state, 'grey'];
  return (
    <span className={`badge ${tone}`}>
      {state === 'GATHERING' && <span className="spinner" aria-hidden="true" />}
      {label}
    </span>
  );
}

export function FixtureBadge() {
  return (
    <span className="badge outline" title="Seeded test data, not a real PayPal dispute">
      FIXTURE
    </span>
  );
}

export function AiLabel({ generator, model }: { generator: 'llm' | 'deterministic'; model: string }) {
  return generator === 'llm' ? (
    <span className="ai-label" title={`Generated by ${model}`}>✦ AI-drafted — review before sending</span>
  ) : (
    <span className="ai-label rules" title="No model was used for this output">
      Rule-based template — review before sending
    </span>
  );
}

export function CompletenessRing({ score, band }: { score: number; band: string }) {
  return (
    <div
      className="meter-ring"
      style={{ ['--pct' as string]: score, ['--col' as string]: BAND_COLOR[band] ?? 'var(--grey)' }}
      role="img"
      aria-label={`Evidence completeness ${score} out of 100, ${band.toLowerCase()}`}
    >
      <div>
        <strong>{score}</strong>
      </div>
    </div>
  );
}

const STEP_GLYPH: Record<WorkflowStepView['status'], string> = {
  pending: '·',
  running: '',
  succeeded: '✓',
  failed: '✕',
  skipped: '–',
};

export function WorkflowSteps({ steps }: { steps: WorkflowStepView[] }) {
  if (steps.length === 0) return <div className="empty small">The evidence workflow has not run yet.</div>;
  return (
    <ol className="steps" aria-live="polite">
      {steps.map((s) => (
        <li className="step" key={s.name}>
          {s.status === 'running' ? (
            <span className="spinner" style={{ marginTop: 3 }} aria-label="running" />
          ) : (
            <span className={`dot ${s.status}`} aria-label={s.status}>
              {STEP_GLYPH[s.status]}
            </span>
          )}
          <div>
            <div style={{ fontWeight: 600 }}>{s.label}</div>
            {s.detail && <div className="muted small">{s.detail}</div>}
            {s.fallbackUsed && <div className="fb">↳ Fallback: {s.fallbackUsed}</div>}
          </div>
          <div className="muted tiny nowrap" style={{ textAlign: 'right' }}>
            {s.durationMs !== null ? `${s.durationMs < 1000 ? `${s.durationMs}ms` : `${(s.durationMs / 1000).toFixed(1)}s`}` : ''}
            {s.attempts > 1 && <div>{s.attempts} attempts</div>}
          </div>
        </li>
      ))}
    </ol>
  );
}

/** Renders text with E-n citations highlighted. */
export function Cited({ text }: { text: string }) {
  const parts = text.split(/(\bE-\d+\b)/g);
  return (
    <>
      {parts.map((p, i) => (/^E-\d+$/.test(p) ? <span key={i} className="cite">{p}</span> : <span key={i}>{p}</span>))}
    </>
  );
}

export function Toast({ tone, children, onClose }: { tone: 'ok' | 'danger' | 'info' | 'warn'; children: ReactNode; onClose: () => void }) {
  useEffect(() => {
    const t = setTimeout(onClose, 9000);
    return () => clearTimeout(t);
  }, [onClose]);
  return (
    <div className={`alert ${tone} toast`} role="status">
      <div className="grow">{children}</div>
      <button className="btn ghost sm" onClick={onClose} aria-label="Dismiss">✕</button>
    </div>
  );
}

export function Alert({ tone, children }: { tone: 'warn' | 'danger' | 'info' | 'ok'; children: ReactNode }) {
  const icon = { warn: '!', danger: '!!', info: 'i', ok: '✓' }[tone];
  return (
    <div className={`alert ${tone}`} role={tone === 'danger' ? 'alert' : 'note'}>
      <span className="icon" aria-hidden="true">{icon}</span>
      <div>{children}</div>
    </div>
  );
}
